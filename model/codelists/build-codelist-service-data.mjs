// UX1 — build UI-consumable codelist service data from the shipped .gc files.
//
// For every codelist the governance registry marks `shipped: true` AND
// `useForUI: true`, emit model/generated/codelists/<name>.json:
//   { codelist, listId?, source, count, codes: [{ code, labels: {lang: text} }] }
// plus an index.json listing every emitted list with its size and languages.
//
// This is the data a front-end codelist service loads on demand (UX1): the form
// lens names a list (`codelist` + `uiType: "code"`), the UI fetches THAT list
// here and renders a picker showing locale-appropriate labels while the stored
// instance keeps the bare code. Decoupled from the JSON Schema on purpose — large
// lists (country 341, currency ~290, occupation 4046) are referenced by name,
// never inlined.
//
// The .gc files are the single source for both the inlined enums (instance
// schema) and this service data, so they cannot drift.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { codelistPath, readCodelistEntries } from './read-codelist.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const governancePath = path.join(here, 'governance.json');
const outDir = path.resolve(here, '..', 'generated', 'codelists');

/** The dated listId URI a .gc declares, if any (for the UI/service metadata). */
function listIdOf(gcFile) {
  const xml = fs.readFileSync(codelistPath(gcFile), 'utf8');
  const idBlock = xml.match(/<Identification>([\s\S]*?)<\/Identification>/)?.[1] ?? xml;
  return idBlock.match(/<LongName\s+Identifier="listId">([^<]+)<\/LongName>/)?.[1];
}

/** Build the service-data files; returns the index object. Pure w.r.t. inputs. */
export function buildCodelistServiceData({ write = true } = {}) {
  const governance = JSON.parse(fs.readFileSync(governancePath, 'utf8'));
  const index = { $comment: 'GENERATED by model/codelists/build-codelist-service-data.mjs. UI codelist service data derived from the shipped ESPD-EDM .gc files for every governance list with shipped && useForUI. Do not hand-edit; regenerate.', codelists: [] };
  const files = [];

  for (const [name, def] of Object.entries(governance.codelists)) {
    if (!def.shipped || !def.useForUI || !def.gc) continue;
    const entries = readCodelistEntries(codelistPath(def.gc));
    const languages = [...new Set(entries.flatMap(e => Object.keys(e.labels)))].sort();
    const doc = {
      $comment: `GENERATED from ESPD-EDM/codelists/${def.gc}. UI pick list for '${name}'. Do not hand-edit; regenerate from the .gc.`,
      codelist: name,
      ...(listIdOf(def.gc) ? { listId: listIdOf(def.gc) } : {}),
      source: def.gc,
      count: entries.length,
      languages,
      codes: entries,
    };
    files.push({ name, doc });
    index.codelists.push({ codelist: name, source: def.gc, count: entries.length, languages });
  }

  index.codelists.sort((a, b) => a.codelist.localeCompare(b.codelist));

  if (write) {
    fs.mkdirSync(outDir, { recursive: true });
    for (const { name, doc } of files) {
      fs.writeFileSync(path.join(outDir, `${name}.json`), JSON.stringify(doc, null, 2) + '\n');
    }
    fs.writeFileSync(path.join(outDir, 'index.json'), JSON.stringify(index, null, 2) + '\n');
  }

  return { index, files };
}

// Run directly: node model/codelists/build-codelist-service-data.mjs
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const { index } = buildCodelistServiceData({ write: true });
  const total = index.codelists.reduce((n, c) => n + c.count, 0);
  console.log(`Generated ${index.codelists.length} UI codelists (${total} codes) under model/generated/codelists.`);
  for (const c of index.codelists) console.log(`  ${c.codelist} (${c.count} codes, ${c.languages.length} langs)`);
}
