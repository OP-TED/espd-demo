// UX1 — build UI codelist service data from the shipped .gc files, following the
// project's i18n KEY mechanism (English-only).
//
// Two coordinated outputs, mirroring how the form lens separates structure from
// text (the lens emits a `labelKey`; the English text lives in the i18n
// catalogue):
//
//   model/generated/codelists/<name>.json
//     { codelist, listId?, source, count, codes: [{ code, labelKey }] }
//     — the STRUCTURE a front-end codelist service loads: codes + their i18n key.
//
//   i18n/i18n/en/espd.codelists.json
//     { "codelist.label.<name>.<code>": "<English label>", ... }
//     — the English TEXT, in the same catalogue the rest of the UI uses. A code
//       with no English label in the source .gc gets no key (the UI falls back
//       to the bare code).
//
// Only lists the governance registry marks `shipped: true` AND `useForUI: true`
// are emitted. English only, by project policy — the .gc files carry 24 EU
// languages, but we take `eng_label` / `name-eng` / `Name` and ignore the rest.
//
// The .gc files are the single source for the inlined enums (instance schema),
// this service data, AND the English catalogue entries, so none can drift.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { codelistPath, readCodelistEntries } from './read-codelist.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const governancePath = path.join(here, 'governance.json');
const outDir = path.resolve(here, '..', 'generated', 'codelists');
const i18nPath = path.resolve(here, '..', '..', 'i18n', 'i18n', 'en', 'espd.codelists.json');

/** The i18n key for one codelist code (documented in i18n/translations.json). */
export function codelistLabelKey(name, code) {
  return `codelist.label.${name}.${code}`;
}

/** The dated listId URI a .gc declares, if any (for the UI/service metadata). */
function listIdOf(gcFile) {
  const xml = fs.readFileSync(codelistPath(gcFile), 'utf8');
  const idBlock = xml.match(/<Identification>([\s\S]*?)<\/Identification>/)?.[1] ?? xml;
  return idBlock.match(/<LongName\s+Identifier="listId">([^<]+)<\/LongName>/)?.[1];
}

/**
 * Build the service-data files + the English i18n catalogue. Returns the index,
 * the per-list docs, and the catalogue object. Pure w.r.t. inputs.
 */
export function buildCodelistServiceData({ write = true } = {}) {
  const governance = JSON.parse(fs.readFileSync(governancePath, 'utf8'));
  const index = { $comment: 'GENERATED by model/codelists/build-codelist-service-data.mjs. UI codelist service data derived from the shipped ESPD-EDM .gc files for every governance list with shipped && useForUI. English labels live in i18n/i18n/en/espd.codelists.json keyed codelist.label.<name>.<code>. Do not hand-edit; regenerate.', codelists: [] };
  const files = [];
  const catalogue = { '_comment': 'GENERATED by model/codelists/build-codelist-service-data.mjs. English labels for codelist codes, keyed codelist.label.<name>.<code>. Source: the shipped ESPD-EDM .gc files (English column only; this project is English-only). Do not hand-edit; regenerate.' };

  for (const [name, def] of Object.entries(governance.codelists)) {
    if (!def.shipped || !def.useForUI || !def.gc) continue;
    // excludedCodes: an ESPD profile narrowing of a shared EU authority table —
    // codes present in the .gc but not valid in the ESPD context (see the
    // governance $excludedCodesNote). Dropped from the UI pick list here; the
    // instance-schema enum and the sync test derive from the same exclusion.
    const excluded = new Set(def.excludedCodes ?? []);
    const entries = readCodelistEntries(codelistPath(def.gc)).filter((e) => !excluded.has(e.code));
    let labelled = 0;
    const codes = entries.map(({ code, label }) => {
      const key = codelistLabelKey(name, code);
      if (label) { catalogue[key] = label; labelled++; }
      return { code, labelKey: key };
    });
    const doc = {
      $comment: `GENERATED from ESPD-EDM/codelists/${def.gc}. UI pick list for '${name}' (codes + i18n label keys; English text in espd.codelists.json). Do not hand-edit; regenerate from the .gc.`,
      codelist: name,
      ...(listIdOf(def.gc) ? { listId: listIdOf(def.gc) } : {}),
      source: def.gc,
      count: codes.length,
      labelled,
      codes,
    };
    files.push({ name, doc });
    index.codelists.push({ codelist: name, source: def.gc, count: codes.length, labelled });
  }

  index.codelists.sort((a, b) => a.codelist.localeCompare(b.codelist));

  if (write) {
    fs.mkdirSync(outDir, { recursive: true });
    for (const { name, doc } of files) {
      fs.writeFileSync(path.join(outDir, `${name}.json`), JSON.stringify(doc, null, 2) + '\n');
    }
    fs.writeFileSync(path.join(outDir, 'index.json'), JSON.stringify(index, null, 2) + '\n');
    fs.mkdirSync(path.dirname(i18nPath), { recursive: true });
    fs.writeFileSync(i18nPath, JSON.stringify(catalogue, null, 2) + '\n');
  }

  return { index, files, catalogue };
}

// Run directly: node model/codelists/build-codelist-service-data.mjs
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const { index, catalogue } = buildCodelistServiceData({ write: true });
  const total = index.codelists.reduce((n, c) => n + c.count, 0);
  const keys = Object.keys(catalogue).filter(k => k !== '_comment').length;
  console.log(`Generated ${index.codelists.length} UI codelists (${total} codes, ${keys} English labels) under model/generated/codelists.`);
  for (const c of index.codelists) console.log(`  ${c.codelist} (${c.count} codes, ${c.labelled} labelled)`);
}
