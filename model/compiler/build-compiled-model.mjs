// 7.3 — the compiled-model envelope.
//
// A single machine-readable manifest, model/generated/compiled-model.json, that
// ties the whole compiled model together in one place: version + provenance,
// the shared value-type set (with per-type request/response bindings and usage),
// the criterion inventory, the codelist governance digest, and the generated-
// layer file counts.
//
// It is the structured sibling of docs/coverage-report.md (both read the same
// collectModel()), intended for programmatic consumers — e.g. a renderer or a
// downstream tool that needs to know "which model version is this, validated
// against which EDM release, covering which criteria and value types".
//
// GENERATED, never hand-edited: a test regenerates it and fails if the committed
// file is stale, so it cannot drift. Wired into `model:compile`.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { collectModel } from './build-coverage-report.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, '..', '..');
const packageJsonPath = path.resolve(repoRoot, 'package.json');
const envelopePath = path.resolve(repoRoot, 'model', 'generated', 'compiled-model.json');

const PART_BY_CONTAINER_NAME = {
  I: 'Procedure & contracting authority',
  II: 'Economic operator',
  III: 'Exclusion grounds',
  IV: 'Selection criteria',
  V: 'Reduction of candidates',
  VI: 'Concluding statements (signature)',
};

/** Build the compiled-model envelope object (pure; deterministic ordering). */
export function buildEnvelope() {
  const model = collectModel();
  const pkg = JSON.parse(fs.readFileSync(packageJsonPath, 'utf8'));

  // Provenance of the value-type set (ResponseDataType.gc release), read from the
  // criteria the registry validated against — identical for all, so take the first.
  const edmShortName = model.criteria[0]?.registryShortName ?? null;
  const edmVersion = model.criteria[0]?.registryVersion ?? null;

  // Value types: name + which sides bind + how many criteria use it.
  const valueTypes = Object.keys(model.valueTypes.valueTypes).sort().map(name => {
    const def = model.valueTypes.valueTypes[name];
    return {
      name,
      request: !!def.requestXml,
      response: !!def.responseXml,
      usedBy: model.valueTypeUsage.get(name) ?? 0,
    };
  });

  // Criterion inventory (sorted by part then id), the stable identity surface.
  const criteria = model.criteria.map(c => ({
    id: c.id,
    eaCode: c.eaCode,
    tag: c.tag ?? null,
    part: c.part,
    leaves: c.leaves,
    repeatableGroups: c.repeatableGroups,
    captions: c.captions,
    valueTypes: c.valueTypes,
  }));

  // Per-part criterion counts.
  const byPart = {};
  for (const c of criteria) byPart[c.part] = (byPart[c.part] ?? 0) + 1;
  const partsCovered = Object.keys(PART_BY_CONTAINER_NAME)
    .filter(p => byPart[p])
    .map(p => ({ part: p, name: PART_BY_CONTAINER_NAME[p], criteria: byPart[p] }));

  // Codelist governance digest (the four axes), sorted by name.
  const codelists = Object.keys(model.governance.codelists).sort().map(name => {
    const g = model.governance.codelists[name];
    return {
      name,
      shipped: !!g.shipped,
      schematronValidated: !!g.schematronValidated,
      useForUI: !!g.useForUI,
      inlineEnum: !!g.inlineEnum,
    };
  });

  // Hand-authored administrative blocks (part dir -> sections).
  const administrativeBlocks = model.parts.map(p => ({ part: p.dir, sections: p.sections }));

  return {
    $comment: 'GENERATED by model/compiler/build-compiled-model.mjs — do not hand-edit. The compiled-model envelope: version + provenance + value types + criterion inventory + codelist governance digest + generated-layer counts. Regenerate with `npm run model:compile`.',
    modelVersion: pkg.version,
    edm: { shortName: edmShortName, version: edmVersion },
    counts: {
      espdParts: model.partsCount,
      eaCriteria: model.eaCriteria.length,
      distinctCriterionCodes: new Set(model.eaCriteria.map(c => c.code)).size,
      modeledCriteria: criteria.length,
      administrativeSections: model.parts.reduce((n, p) => n + p.sections.length, 0),
      valueTypes: valueTypes.length,
      codelists: codelists.length,
    },
    generated: {
      instanceData: model.generated['instance-data'],
      xmlMapping: model.generated['xml-mapping'],
      formStructure: model.generated['form-structure'],
      codelists: model.generated['codelists'],
    },
    partsCovered,
    valueTypes,
    criteria,
    administrativeBlocks,
    codelists,
  };
}

/** Build and (optionally) write the envelope. Returns the object. */
export function buildCompiledModel({ write = true } = {}) {
  const envelope = buildEnvelope();
  if (write) {
    fs.mkdirSync(path.dirname(envelopePath), { recursive: true });
    fs.writeFileSync(envelopePath, JSON.stringify(envelope, null, 2) + '\n');
  }
  return envelope;
}

export { envelopePath };

// Run directly: node model/compiler/build-compiled-model.mjs
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const env = buildCompiledModel({ write: true });
  process.stderr.write(
    `Wrote ${path.relative(process.cwd(), envelopePath)} ` +
    `(model ${env.modelVersion}, EDM ${env.edm.version}, ` +
    `${env.counts.modeledCriteria} criteria, ${env.counts.valueTypes} value types).\n`);
}
